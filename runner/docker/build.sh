#!/usr/bin/env bash
# Build the kiln-perf image (runner/docker/README.md): stage the runner, the CUDA launcher, the device probe and freshly
# generated launcher fixtures into a context directory, then build it here or on a GPU host over SSH.
set -euo pipefail

usage() {
  cat <<'USAGE'
usage: runner/docker/build.sh [--host USER@HOST] [--tag NAME:TAG] [--cuda VERSION] [--ncu] [--context-only DIR]

  --host USER@HOST     build on that machine: the context is streamed to `docker build -` as a tar over SSH
  --tag NAME:TAG       image tag (default kiln-perf:<revision>-cuda<VERSION>, <revision> with -dirty when the staged
                       sources differ from HEAD); kiln-perf:latest is always set too
  --cuda VERSION       CUDA toolkit from NVIDIA's apt repository (default 13.0; the host driver must support it)
  --ncu                include Nsight Compute (ncu) for the runner's --ncu profiling
  --context-only DIR   stage the build context into DIR and stop
USAGE
}

host="" tag="" cuda=13.0 ncu=0 only=""
while [ $# -gt 0 ]; do
  case $1 in
    --host) host=$2; shift 2 ;;
    --tag) tag=$2; shift 2 ;;
    --cuda) cuda=$2; shift 2 ;;
    --ncu) ncu=1; shift ;;
    --context-only) only=$2; shift 2 ;;
    -h | --help) usage; exit 0 ;;
    *) usage >&2; exit 2 ;;
  esac
done

root=$(cd "$(dirname "$0")/../.." && pwd)
here=$root/runner/docker
if [ -n "$only" ]; then mkdir -p "$only"; ctx=$(cd "$only" && pwd); else ctx=$(mktemp -d); trap 'rm -rf "$ctx"' EXIT; fi

cp "$root/runner/kiln_runner.py" "$root/runtime/python/kiln_launch.py" "$here/Dockerfile" "$here/kiln-probe.cu" \
  "$here/kiln-probe" "$here/kiln-selftest" "$ctx/"
(cd "$root" && node runtime/test/fixtures.mjs "$ctx/fixtures" >/dev/null)
[ -n "$only" ] && { echo "context in $ctx"; exit 0; }

# the fixtures are generated by the compiler, so its sources count towards the revision too
rev=$(git -C "$root" rev-parse --short HEAD)
if [ -n "$(git -C "$root" status --porcelain -- runner runtime/python runtime/test packages/kiln/src apps/workbench/src apps/workbench/presets)" ]; then
  rev=$rev-dirty
fi
tag=${tag:-kiln-perf:$rev-cuda$cuda}
sha() { shasum -a 256 "$1" 2>/dev/null | cut -d' ' -f1 || sha256sum "$1" | cut -d' ' -f1; }
args=(--build-arg "CUDA_VERSION=$cuda" --build-arg "WITH_NCU=$ncu" --build-arg "KILN_REVISION=$rev"
  --build-arg "RUNNER_SHA256=$(sha "$ctx/kiln_runner.py")" --build-arg "LAUNCHER_SHA256=$(sha "$ctx/kiln_launch.py")"
  -t "$tag" -t kiln-perf:latest)

if [ -n "$host" ]; then
  q=$(printf '%q ' "${args[@]}")
  # macOS tar otherwise adds an AppleDouble ._<name> file for every file with extended attributes (COPYFILE_DISABLE),
  # which the launcher's check reads as a fixture, or a pax header for them (--no-xattrs). The context is unpacked into
  # a directory on the host rather than piped to `docker build -`, which must guess whether stdin is a tar.
  COPYFILE_DISABLE=1 tar --no-xattrs -C "$ctx" -cf - . |
    ssh -o BatchMode=yes "$host" "d=\$(mktemp -d) && tar -C \"\$d\" -xf - && docker build $q \"\$d\"; rc=\$?; rm -rf \"\$d\"; exit \$rc"
else
  docker build "${args[@]}" "$ctx"
fi
echo "built $tag${host:+ on $host}"
